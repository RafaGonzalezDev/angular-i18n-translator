/**
 * Step 1: Ask for API Key
 */
async function askApiKey() {
  const apiKey = await password({
    message: 'Enter your LLM API key',
    mask: '*',
    validate: (value) => {
      if (!value || value.trim().length === 0) {
        return 'API key is required';
      }
      return true;
    }
  });
  
  return apiKey.trim();
}

/**
 * Step 2: Select LLM Provider
 */
async function askProvider() {
  const provider = await select({
    message: 'Select your LLM provider',
    choices: LLM_PROVIDERS,
    pageSize: 8
  });
  
  return provider;
}

/**
 * Step 2b: Ask for model name based on selected provider
 */
async function askModel(provider) {
  const { input } = await import('@inquirer/prompts');
  
  const model = await input({
    message: `Enter model name for ${provider.name} (see: ${provider.docsURL}):`,
    validate: (value) => {
      if (!value || value.trim().length === 0) {
        return 'Model name is required. Please check the documentation link above for available models.';
      }
      return true;
    }
  });
  
  return model.trim();
}

/**
 * Step 3: Ask for custom URL and model (if needed)
 */
async function askCustomProviderConfig(provider) {
  if (!provider.isCustom) {
    return provider;
  }
  
  console.log();
  
  const baseURL = await input({
    message: 'Enter API base URL',
    validate: (value) => {
      if (!value || value.trim().length === 0) {
        return 'URL is required';
      }
      if (!value.startsWith('http://') && !value.startsWith('https://')) {
        return 'URL must start with http:// or https://';
      }
      return true;
    }
  });
  
  const model = await input({
    message: 'Enter model name',
    validate: (value) => {
      if (!value || value.trim().length === 0) {
        return 'Model name is required';
      }
      return true;
    }
  });
  
  return { baseURL: baseURL.trim(), model: model.trim() };
}

/**
 * Step 4: Select Source Language
 */
async function askSourceLanguage() {
  const { confirm, select } = await import('@inquirer/prompts');
  
  // Primero preguntar si usar inglés como default
  const useEnglish = await confirm({
    message: 'Use English as the source language?',
    default: true
  });
  
  if (useEnglish) {
    return 'en';
  }
  
  // Si no, mostrar lista completa
  const sourceLanguage = await select({
    message: 'Select source language (the language of your original XLF file)',
    choices: getLanguageChoices(),
    pageSize: 10
  });
  
  return sourceLanguage;
}

/**
 * Step 5: Select Target Languages
 */
async function askTargetLanguages(sourceLanguage) {
  const availableTargets = getLanguageChoices().filter(l => l.value !== sourceLanguage);
  
  const targetLanguages = await checkbox({
    message: 'Select target languages (languages to translate TO)',
    choices: availableTargets,
    pageSize: 12,
    validate: (choices) => {
      if (!choices || choices.length === 0) {
        return 'Please select at least one target language';
      }
      return true;
    }
  });
  
  return targetLanguages;
}

/**
 * Step 6: Batch Settings (optional)
 */
async function askBatchSettings() {
  const customizeBatch = await confirm({
    message: 'Customize batch settings?',
    default: false
  });
  
  if (!customizeBatch) {
    return { batchSize: 50, concurrency: 5 };
  }
  
  console.log();
  
  const batchSizeInput = await input({
    message: 'Records per batch',
    default: '50',
    validate: (value) => {
      const num = parseInt(value, 10);
      if (isNaN(num) || num < 1) {
        return 'Must be a positive number';
      }
      if (num > 200) {
        return 'Batch size should not exceed 200 for best results';
      }
      return true;
    }
  });
  
  const concurrencyInput = await input({
    message: 'Concurrent batches per language',
    default: '5',
    validate: (value) => {
      const num = parseInt(value, 10);
      if (isNaN(num) || num < 1) {
        return 'Must be a positive number';
      }
      if (num > 20) {
        return 'Concurrency should not exceed 20 to avoid rate limits';
      }
      return true;
    }
  });
  
  return {
    batchSize: parseInt(batchSizeInput, 10),
    concurrency: parseInt(concurrencyInput, 10)
  };
}

