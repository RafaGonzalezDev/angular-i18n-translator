/**
 * Build language config entries
 */
function buildLanguageConfig(sourceLanguage, targetLanguages) {
  const languages = [
    { 
      code: sourceLanguage, 
      name: getLanguageDisplayName(sourceLanguage), 
      file: `messages.${sourceLanguage}.xlf` 
    }
  ];
  
  for (const targetCode of targetLanguages) {
    languages.push({
      code: targetCode,
      name: getLanguageDisplayName(targetCode),
      file: `messages.${targetCode}.xlf`
    });
  }
  
  return languages;
}

/**
 * Generate i18n.config.json content
 */
function generateConfig(languages, sourceLanguage, batchSettings, providerName) {
  const llm = {
    baseURL: '${LLM_BASE_URL}',
    apiKey: '${LLM_API_KEY}',
    model: '${LLM_MODEL}',
    batchSize: batchSettings.batchSize,
    concurrency: batchSettings.concurrency,
    timeoutMs: 300000
  };

  // DeepSeek models think by default; translation does not need it and
  // disabling it makes requests much faster and cheaper.
  if (providerName === 'DeepSeek') {
    llm.requestExtra = { thinking: { type: 'disabled' } };
  }

  return {
    languages,
    sourceLanguage,
    sourceFile: 'messages.xlf',
    csvOutput: 'messages.csv',
    outputDir: 'dist-i18n',
    batchDir: 'batches',
    llm
  };
}

/**
 * Generate .env content
 */
function generateEnv(apiKey, baseURL, model) {
  let content = `# Angular i18n Translator Configuration
# Generated by 'init' command

LLM_API_KEY=${apiKey}
LLM_BASE_URL=${baseURL}
LLM_MODEL=${model}
`;
  return content;
}

/**
 * Check if .env exists and merge API key
 */
function updateEnvFile(envPath, apiKey, baseURL, model) {
  let content = '';
  
  if (existsSync(envPath)) {
    content = readFileSync(envPath, 'utf-8');
    
    // Update or add each variable
    const updates = [
      { key: 'LLM_API_KEY', value: apiKey },
      { key: 'LLM_BASE_URL', value: baseURL },
      { key: 'LLM_MODEL', value: model }
    ];
    
    for (const { key, value } of updates) {
      const regex = new RegExp(`^${key}=.*$`, 'm');
      if (regex.test(content)) {
        content = content.replace(regex, `${key}=${value}`);
      } else {
        // Add to end if not present
        content += `\n${key}=${value}`;
      }
    }
  } else {
    content = generateEnv(apiKey, baseURL, model);
  }
  
  return content;
}

