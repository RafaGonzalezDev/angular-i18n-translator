/**
 * Main init command handler
 */
async function handleInit() {
  printHeader('Interactive Configuration Wizard');
  
  const cwd = process.cwd();
  const envPath = resolve(cwd, '.env');
  const configPath = resolve(cwd, 'i18n.config.json');
  
  // Check for existing config
  if (existsSync(configPath)) {
    console.log(colors.warning('⚠ An i18n.config.json file already exists.'));
    const overwrite = await confirm({
      message: 'Do you want to overwrite it?',
      default: false
    });
    
    if (!overwrite) {
      console.log(colors.dim('Configuration cancelled.'));
      return 0;
    }
  }
  
  console.log(colors.dim('This wizard will help you set up your i18n translation configuration.\n'));
  
  // Step 1: API Key
  const apiKey = await askApiKey();
  
  // Step 2: LLM Provider
  const provider = await askProvider();

  // Step 3: Provider-specific details (URL + model for custom providers)
  let providerConfig;
  if (provider.isCustom) {
    providerConfig = await askCustomProviderConfig(provider);
  } else {
    const model = await askModel(provider);
    providerConfig = { ...provider, model };
  }
  
  // Step 4: Source Language
  const sourceLanguage = await askSourceLanguage();
  
  // Step 5: Target Languages
  const targetLanguages = await askTargetLanguages(sourceLanguage);
  
  // Step 6: Batch Settings
  const batchSettings = await askBatchSettings();
  
  // Build configuration
  const languages = buildLanguageConfig(sourceLanguage, targetLanguages);
  const config = generateConfig(languages, sourceLanguage, batchSettings, provider.name);
  
  // Replace placeholders for display (actual config uses env vars)
  const displayConfig = {
    ...config,
    llm: {
      ...config.llm,
      baseURL: providerConfig.baseURL,
      apiKey: '***',
      model: providerConfig.model
    }
  };
  
  // Step 7: Summary and confirmation
  const confirmed = await showSummary(displayConfig, envPath, configPath);
  
  if (!confirmed) {
    console.log(colors.dim('\nConfiguration cancelled.'));
    return 0;
  }
  
  // Create files
  const spinner = createSpinner('Creating configuration files...');
  spinner.start();
  
  try {
    // Update/create .env file
    const envContent = updateEnvFile(envPath, apiKey, providerConfig.baseURL, providerConfig.model);
    writeFileSync(envPath, envContent, 'utf-8');
    
    // Create i18n.config.json
    const configJson = JSON.stringify(config, null, 2);
    writeFileSync(configPath, configJson, 'utf-8');
    
    spinner.succeed('Configuration files created successfully!');
    
    // Add .env to .gitignore if not present
    const gitignorePath = resolve(cwd, '.gitignore');
    if (existsSync(gitignorePath)) {
      const gitignore = readFileSync(gitignorePath, 'utf-8');
      if (!gitignore.includes('.env')) {
        const updatedGitignore = gitignore.trimEnd() + '\n\n# Environment variables\n.env\n';
        writeFileSync(gitignorePath, updatedGitignore, 'utf-8');
        console.log(colors.success('✓ Added .env to .gitignore'));
      }
    }
    
    // Show success message and next steps
    console.log();
    console.log(colors.success('✓ Configuration complete!'));
    
    showNextSteps();
    
    return 0;
  } catch (error) {
    spinner.fail(`Failed to create configuration: ${error.message}`);
    return 1;
  }
}

export default handleInit;
